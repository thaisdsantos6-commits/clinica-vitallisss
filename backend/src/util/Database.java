package util;

import java.net.URI;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

public final class Database {
    private static final String URL = System.getenv("DATABASE_URL");
    private static final String USER = System.getenv("DATABASE_USER");
    private static final String PASSWORD = System.getenv("DATABASE_PASSWORD");

    private Database() {
    }

    public static Connection conectar() {
        if (URL == null || URL.isBlank()) {
            throw new IllegalStateException("Configure a variável DATABASE_URL para conectar ao PostgreSQL.");
        }
        try {
            String jdbcUrl = URL.strip();
            if (jdbcUrl.startsWith("postgres://") || jdbcUrl.startsWith("postgresql://")) {
                URI uri = URI.create(jdbcUrl);
                String host = uri.getHost();
                if (host == null) throw new IllegalArgumentException("Host ausente em DATABASE_URL.");

                String caminho = uri.getRawPath() == null ? "" : uri.getRawPath();
                String parametros = uri.getRawQuery() == null ? "" : "?" + uri.getRawQuery();
                jdbcUrl = "jdbc:postgresql://" + host
                        + (uri.getPort() < 0 ? "" : ":" + uri.getPort())
                        + caminho + parametros;

                String usuarioSenha = uri.getUserInfo();
                if (usuarioSenha != null) {
                    int separador = usuarioSenha.indexOf(':');
                    String usuario = separador < 0 ? usuarioSenha : usuarioSenha.substring(0, separador);
                    String senha = separador < 0 ? "" : usuarioSenha.substring(separador + 1);
                    return DriverManager.getConnection(jdbcUrl, usuario, senha);
                }
            }

            if (USER != null && PASSWORD != null) {
                return DriverManager.getConnection(jdbcUrl, USER, PASSWORD);
            }
            return DriverManager.getConnection(jdbcUrl);
        } catch (SQLException e) {
            throw new DatabaseException("Não foi possível conectar ao PostgreSQL.", e.getSQLState(), e);
        } catch (IllegalArgumentException e) {
            throw new IllegalStateException("DATABASE_URL inválida. Use a URL JDBC do PostgreSQL ou a URL do Render.", e);
        }
    }

    public static void inicializar() {
        String pacientes = "CREATE TABLE IF NOT EXISTS pacientes ("
                + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "nome VARCHAR(100) NOT NULL,"
                + "cpf VARCHAR(11) NOT NULL UNIQUE,"
                + "convenio VARCHAR(60) NOT NULL,"
                + "foto TEXT,"
                + "historico TEXT NOT NULL DEFAULT '')";
        String consultas = "CREATE TABLE IF NOT EXISTS consultas ("
                + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "paciente_id INTEGER NOT NULL REFERENCES pacientes(id) ON DELETE CASCADE,"
                + "medico VARCHAR(80) NOT NULL,"
                + "data_hora TIMESTAMP NOT NULL,"
                + "status VARCHAR(30) NOT NULL DEFAULT 'AGENDADA',"
                + "orcamento_centavos BIGINT CHECK (orcamento_centavos IS NULL OR orcamento_centavos >= 0))";
        String horarioUnico = "CREATE UNIQUE INDEX IF NOT EXISTS consultas_medico_horario_unico "
                + "ON consultas (LOWER(medico), data_hora)";

        try (Connection conexao = conectar();
             java.sql.Statement statement = conexao.createStatement()) {
            statement.execute(pacientes);
            statement.execute(consultas);
            statement.execute(horarioUnico);
        } catch (SQLException e) {
            throw new DatabaseException("Não foi possível inicializar as tabelas do PostgreSQL.", e.getSQLState(), e);
        }
    }
}
